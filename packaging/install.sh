#!/usr/bin/env bash
# Install Gemini for Linux for the current user (no root required).
#
#   ./packaging/install.sh [--uninstall]
#
# Installs a launcher on PATH, a desktop entry and icons, so the app appears in
# the application menu and can be bound to a global shortcut.
set -euo pipefail

APP_ID="dev.gemini.GeminiDesktop"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN_DIR="${HOME}/.local/bin"
APP_DIR="${HOME}/.local/share/applications"
ICON_ROOT="${HOME}/.local/share/icons/hicolor"
LAUNCHER="${BIN_DIR}/gemini-desktop"
DESKTOP="${APP_DIR}/${APP_ID}.desktop"

if [[ "${1:-}" == "--uninstall" ]]; then
  rm -f "${LAUNCHER}" "${DESKTOP}"
  for s in 16 24 32 48 64 128 256 512; do rm -f "${ICON_ROOT}/${s}x${s}/apps/${APP_ID}.png"; done
  command -v update-desktop-database >/dev/null && update-desktop-database "${APP_DIR}" || true
  command -v gtk-update-icon-cache >/dev/null && gtk-update-icon-cache -f -t "${ICON_ROOT}" || true
  echo "Removed ${APP_ID}."
  exit 0
fi

mkdir -p "${BIN_DIR}" "${APP_DIR}"

# --- launcher ---------------------------------------------------------------
# gtk4-layer-shell has to be preloaded ahead of libwayland or it cannot install
# its protocol handlers; the overlay falls back to a normal window without it.
cat > "${LAUNCHER}" <<EOF
#!/usr/bin/env bash
# Generated by packaging/install.sh
set -euo pipefail
APP_DIR="${HERE}"
if [[ -z "\${GEMINI_NO_LAYER_SHELL:-}" ]] && [[ -z "\${LD_PRELOAD:-}" ]]; then
  for lib in /usr/lib/libgtk4-layer-shell.so /usr/lib64/libgtk4-layer-shell.so; do
    if [[ -e "\$lib" ]]; then export LD_PRELOAD="\$lib"; break; fi
  done
fi
export PYTHONPATH="\${APP_DIR}:\${PYTHONPATH:-}"
exec python3 -m app.main "\$@"
EOF
chmod +x "${LAUNCHER}"

# --- icons ------------------------------------------------------------------
# Optional: `assets/icons/appicon_<size>.png` is used when present. The repo
# does not ship one (see assets/README.md), so the menu entry falls back to a
# stock icon rather than pointing at a missing file.
DESKTOP_ICON="applications-internet"
for s in 16 24 32 48 64 128 256 512; do
  src="${HERE}/assets/icons/appicon_${s}.png"
  dir="${ICON_ROOT}/${s}x${s}/apps"
  if [[ -f "${src}" ]]; then
    mkdir -p "${dir}"
    cp "${src}" "${dir}/${APP_ID}.png"
    DESKTOP_ICON="${APP_ID}"
  fi
done

# --- desktop entry ----------------------------------------------------------
cat > "${DESKTOP}" <<EOF
[Desktop Entry]
Type=Application
Name=Gemini
Comment=Gemini desktop client, native for Linux
Exec=${LAUNCHER} %U
Icon=${DESKTOP_ICON}
Terminal=false
Categories=Utility;Network;InstantMessaging;
StartupNotify=true
StartupWMClass=${APP_ID}
EOF

command -v update-desktop-database >/dev/null && update-desktop-database "${APP_DIR}" || true
command -v gtk-update-icon-cache >/dev/null && gtk-update-icon-cache -f -t "${ICON_ROOT}" || true

cat <<EOF
Installed Gemini for Linux.

  launcher : ${LAUNCHER}
  entry    : ${DESKTOP}

Run it:                 gemini-desktop
Quick chat overlay:     gemini-desktop --quick

Bind quick chat to a key in your compositor, for example:

  GNOME    Settings > Keyboard > Custom Shortcuts > gemini-desktop --quick
  Hyprland bind = SUPER, SPACE, exec, gemini-desktop --quick
  sway     bindsym \$mod+space exec gemini-desktop --quick
  KDE      System Settings > Shortcuts > Custom > gemini-desktop --quick
EOF
